package au.mapbot.apex.classes;

import org.opencv.core.Point;

public class Line {
    Point start;
    Point end;

    // No-argument constructor
    public Line() {
    }

    public Line(Point start, Point end) {
        this.start = start;
        this.end = end;
    }

    public Point getStart() {
        return start;
    }

    public void setStart(Point start) {
        this.start = start;
    }

    public Point getEnd() {
        return end;
    }

    public void setEnd(Point end) {
        this.end = end;
    }
}
